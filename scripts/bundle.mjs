// Bundles each page's ES modules into one classic script under dist/, so the pages also work when opened
// straight from disk (browsers refuse to load ES modules over file://). No dependencies.
//
//   node scripts/bundle.mjs           write dist/
//   node scripts/bundle.mjs --check   exit 1 if dist/ is out of date
//
// Supports only the module forms this repo uses:
//   import * as X from "./m.js";   import { a, b } from "./m.js";   export function|const|let|class name
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRIES = { "create.js": "js/wizard.js", "decode.js": "js/decode.js" };

const IMPORT = /^import\s+(?:\*\s+as\s+(\w+)|\{([^}]*)\})\s+from\s+"(\.\/[\w.-]+)";\s*$/gm;
const EXPORT = /^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([\w$]+)/gm;

function bundle(entry) {
  const order = [];
  const seen = new Set();
  const visit = (rel) => {
    if (seen.has(rel)) return;
    seen.add(rel);
    const src = readFileSync(join(root, rel), "utf8");
    for (const m of src.matchAll(IMPORT)) visit(join(dirname(rel), m[3]));
    order.push(rel);
  };
  visit(entry);

  const id = (rel) => "__" + rel.replace(/^js\//, "").replace(/\W/g, "_");
  const parts = order.map((rel) => {
    let src = readFileSync(join(root, rel), "utf8");
    const exported = [...src.matchAll(EXPORT)].map((m) => m[1]);
    src = src.replace(IMPORT, (_, ns, names, from) => {
      const dep = id(join(dirname(rel), from));
      return ns ? `const ${ns} = ${dep};` : `const {${names}} = ${dep};`;
    });
    src = src.replace(/^export\s+/gm, "");
    if (/^\s*(import|export)\b/m.test(src)) throw new Error(`${rel}: unsupported import/export form`);
    return `// ---- ${rel}\nconst ${id(rel)} = (() => {\n${src}\nreturn { ${exported.join(", ")} };\n})();`;
  });
  return `// Generated by scripts/bundle.mjs from ${entry} — do not edit; edit js/ and re-run.\n"use strict";\n(() => {\n${parts.join("\n\n")}\n})();\n`;
}

const check = process.argv.includes("--check");
let stale = [];
mkdirSync(join(root, "dist"), { recursive: true });
for (const [out, entry] of Object.entries(ENTRIES)) {
  const path = join(root, "dist", out);
  const code = bundle(entry);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== code) stale.push(`dist/${out}`);
  } else {
    writeFileSync(path, code);
    console.log(`wrote dist/${out} (${code.length} bytes)`);
  }
}
if (stale.length) {
  console.error(`out of date: ${stale.join(", ")} — run: npm run build`);
  process.exit(1);
}
